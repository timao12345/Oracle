-- Verifica o STATUS do BACKUP RMAN

SET PAGES 9999
SET LINES 200
COL OPERATION FORMAT A10 TRUNC
COL MB_COPIADOS FORMAT 9,999,999.99
COL STATUS FOR A30
COL BEGIN FOR A20
COL END FOR A20

PROMPT 'VERIFICAR O BACKUP DO BANCO DE DADOS'

SELECT TO_CHAR(start_time,'DD/MM/YYYY HH24:MI dy') 
	BEGIN, TO_CHAR(end_time,'DD/MM/YYYy HH24:MI dy') 
	END, operation,
	OBJECT_TYPE, 
	STATUS,
	OUTPUT_DEVICE_TYPE 
	DEVICE, 
	MBYTES_PROCESSED MB_COPIADOS,
	OUTPUT_DEVICE_TYPE
FROM V$RMAN_STATUS
WHERE START_TIME > SYSDATE -10
AND OPERATION='BACKUP'
ORDER  BY END_TIME DESC
