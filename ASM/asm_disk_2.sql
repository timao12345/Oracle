SET LINES 200 PAGES 500
COL NAME FOR A30
COL PATH FOR A50

UNDEF DISKGROUP
SELECT  a.GROUP_NUMBER,
  b.name "NAME_DISKGROUP",
  a.DISK_NUMBER,
  a.NAME "NAME_DISK",
  a.PATH,
  a.HEADER_STATUS,
  a.MOUNT_STATUS,	
  a.STATE,
  a.MODE_STATUS,
  a.TOTAL_MB,
  a.FREE_MB
FROM  V$ASM_DISK a, 
  V$ASM_DISKGROUP b
WHERE  a.GROUP_NUMBER=b.GROUP_NUMBER 
AND  b.NAME =('&&DISKGROUP')  
ORDER BY a.NAME, b.NAME;