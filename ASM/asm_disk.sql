-- Verificar os discos e os diskgroups disponiveis.

SET LINES 200 PAGES 500
COL NAME FOR A25
COL PATH FOR A40
SELECT 
	GROUP_NUMBER,
	DISK_NUMBER,
	NAME,
	PATH,
	HEADER_STATUS,
	MOUNT_STATUS,
	STATE,
	MODE_STATUS,
	TOTAL_MB,
	FREE_MB 
FROM 
	V$ASM_DISK ORDER BY 1,3,4;


SELECT GROUP_NUMBER, NAME DISKGROUP, STATE, TOTAL_MB, FREE_MB, (TOTAL_MB-FREE_MB)/TOTAL_MB*100 PCT_UTILIZADO FROM GV$ASM_DISKGROUP where name not in ('REDOC');