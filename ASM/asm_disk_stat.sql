-- Verificar os STATUS dos DG

COL LABEL FOR A15
COL PATH FOR A40
SET PAGES 80
COL NAME FOR A20

SELECT 
	GROUP_NUMBER,
	DISK_NUMBER,
	MOUNT_STATUS,
	HEADER_STATUS,
	MODE_STATUS,
	STATE,
	NAME,
	FAILGROUP,
	PATH,
	TOTAL_MB,
	FREE_MB, round((TOTAL_MB-FREE_MB)/TOTAL_MB*100)"PCT_UTILIZADO %"
FROM 
	V$ASM_DISK_STAT
ORDER BY 1;

