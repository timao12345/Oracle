SET LINES 900 PAGES 90
COL COMPATIBILITY FOR A20
COL DATABASE_COMPATIBILITY FOR A20 HEADING 'DATABASE|COMPATIBILITY'
COL DATABASE_COMPATIBILITY FOR A15 HEADING 'DATABASE|COMPATIBILITY'

SELECT 
	NAME,
	TYPE,
	STATE, 
	ROUND(TOTAL_MB/1024,2) TOTAL_GB, 
	ROUND(FREE_MB/1024,2) FREE_GB,
    ROUND(FREE_MB/TOTAL_MB*100,2) "%_FREE",
	ROUND((TOTAL_MB-FREE_MB)/TOTAL_MB*100,2) "%_UTILIZED",
    ALLOCATION_UNIT_SIZE/1024/1024 A_U_S, 
	COMPATIBILITY, 
	DATABASE_COMPATIBILITY
FROM 
	V$ASM_DISKGROUP
WHERE 
	TOTAL_MB > 1;