-- faça um node por vez.
dbaascli grid upgrade --version grid_version [--targethome oracle_home] [--containerUrl container] [--executePrereqs] [--skipPrereqs] [--ignorePrereqFailure] [--resume] [--revert]

-version grid_version— especifica a versão do Oracle Grid Infrastructure para a qual você deseja atualizar.

--targethome oracle_home— especifica opcionalmente o caminho para o diretório existente do Oracle Grid Infrastructure.

--containerUrl container— especifica opcionalmente os arquivos de imagem do Oracle Grid Infrastructure a serem usados ​​para a atualização. 
    --  O local é especificado como um URL para um contêiner de armazenamento em nuvem que contém as imagens do software.Normalmente, 
    --  essa --containerUrlopção não é necessária, pois a localização da biblioteca de imagens de software é derivada automaticamente das informações de configuração no ambiente Exadata Cloud at Customer . 
    --  No entanto, se você tiver alguma dificuldade com a localização automática, poderá abrir uma solicitação de serviço (SR) com o Suporte da Oracle, 
    --  que poderá orientá-lo a usar essa opção para especificar uma localização alternativa.

--executePrereqs— Opcionalmente, realiza uma verificação de pré-requisitos. Você pode usar essa opção para testar o ambiente antes de realizar uma atualização.
--skipPrereqs— opcionalmente, ignora as verificações de pré-requisitos.
--ignorePrereqFailure— Opcionalmente, ignora a falha em uma verificação de pré-requisito. Você pode usar esta opção para realizar a atualização mesmo que uma verificação de pré-requisito falhe.
--resume— Opcionalmente, retoma uma atualização. Você pode usar esta opção para retomar uma atualização após resolver o problema que causou uma falha anterior na atualização.
--revert— Opcionalmente, realiza um downgrade de versão. Use esta opção somente após uma falha na atualização e com a orientação do Suporte da Oracle.

-- executar o prereqs para verificar se o ambiente está pronto para a atualização.
dbaascli grid upgrade --version 23.26.1.0.0 --executePrereqs

-- Execute o Upgrade caso não gere erro no prereqs.
dbaascli grid upgrade --targetVersion 23.26.1.0.0


