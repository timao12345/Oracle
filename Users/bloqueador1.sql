SET TERMOUT OFF
SET LINES 300 PAGES 80
COL USERNAME FOR A15
COL SPID FOR 999999 
COL OSUSER FOR A20
COL BLOQUEADOR FOR A60
SELECT SUBSTR(DECODE(L.REQUEST,0,'BLOQUEADOR: ','BLOQUEADO: ')||L.SID,1,20) SESSAO,
	S.USERNAME,
--	S.SID,
	S.SERIAL#,
--	B.SPID,
	S.STATUS,
--	S.EVENT,
--	S.OSUSER,
--	S.MACHINE,
--	S.PROGRAM,
--	L.ID1,
--	L.ID2,
-- 	L.LMODE,
-- 	L.REQUEST,
--	L.TYPE,
	L.INST_ID INSTANCE,
	TO_CHAR(S.LOGON_TIME,'DD-MM-RR HH24:MI:SS') LOGON_TIME,
	'ALTER SYSTEM KILL SESSION ''' || S.SID || ',' || S.SERIAL# || ',@'||L.INST_ID||''' IMMEDIATE;' BLOQUEADOR
FROM 
	GV$LOCK L,
	GV$SESSION S,
	V$PROCESS B
WHERE S.PADDR=B.ADDR
AND S.SID=L.SID
AND (L.ID1, L.ID2, L.TYPE) IN
   (SELECT L.ID1, L.ID2, L.TYPE FROM GV$LOCK L WHERE L.REQUEST>0)
     ORDER BY L.ID1, L.REQUEST;
	 
SET LINES 300 PAGES 5000
SET LONG 3000
COL USERNAME 	FOR A15
COL OSUSER 		FOR A15
COL SQL_ID		FOR A15 HEADING 'SQL|ID'
COL LOGON_TIME 	FOR A20 HEADING 'LOGON|TIME'
COL SQL_TEXT	FOR A90

BREAK ON USERNAME NODUP ON SID NODUP ON SERIAL# NODUP ON STATUS NODUP ON OSUSER NODUP ON SQL_ID NODUP ON LOGON_TIME ON INST_ID NODUP SKIP 5

UNDEF SID
ALTER SESSION SET NLS_DATE_FORMAT='dd/mm/yy:hh24:mi:ss';
SELECT A.USERNAME, 
--	A.INST_ID,
	A.SID, 
	A.SERIAL#, 
	A.STATUS,
	A.OSUSER,
	B.SQL_ID, 
	A.LOGON_TIME,
	B.SQL_TEXT
FROM GV$SESSION A, 
	GV$SQLTEXT B
WHERE A.SQL_HASH_VALUE=B.HASH_VALUE
AND A.INST_ID=B.INST_ID
AND SID=&&SID
ORDER BY PIECE
