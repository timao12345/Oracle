SELECT INST_ID, USERNAME, STATUS, OSUSER, to_char(LOGON_TIME,'dd/mm/yyyy hh24:mi:ss'), LAST_CALL_ET/60
FROM GV$SESSION WHERE STATUS='ACTIVE' ORDER BY 5;


select SID, USERNAME,MACHINE, PROGRAM, to_char(LOGON_TIME,'dd/mm/yyyy hh24:mi:ss'), LAST_CALL_ET from v$session where PROGRAM like '%rman%' 
and to_char(LOGON_TIME,'dd/mm/yyyy hh24:mi:ss') < '11/01/2015 15:36:21';


SELECT INST_ID, SID, USERNAME, STATUS, OSUSER, to_char(LOGON_TIME,'dd/mm/yyyy hh24:mi:ss'), LAST_CALL_ET/60 
FROM GV$SESSION WHERE SID IN (2385,1643,351,1611,1647,2776) ORDER BY 5;


