Comandos executados:

Na sequencia, cria a tabela para guardar as estatisticas, exporta fazendo o backup e aplica estatistica.


SQL> EXEC DBMS_STATS.CREATE_STAT_TABLE ('WAPPA_TECH_HOM','BKP_STATS_WAPPA_TECH_HOM','USERS');
EXEC DBMS_STATS.EXPORT_SCHEMA_STATS(ownname=>'WAPPA_TECH_HOM', stattab=>'BKP_STATS_WAPPA_TECH_HOM', statown=>'WAPPA_TECH_HOM');
EXEC DBMS_STATS.GATHER_SCHEMA_STATS('SMW',estimate_percent=>100, cascade=>true )


