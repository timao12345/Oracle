SET LINESIZE 160
SET PAGESIZE 66
SET SPACE 1

COL C1 FOR A15 HEADING "OSUSER"
COL C2 FOR A16 HEADING "USERNAME"
COL B1 FOR A10 HEADING "SPID"
COL B2 FOR 9999 JUSTIFY LEFT
COL B2 HEADING "SID"
COL B3 FOR 999999 JUSTIFY LEFT
COL B3 HEADING "SERIAL#"
COL B4 FOR A10 HEADING "STATUS"
COL B5 FOR A20 HEADING "LOGON_TIME"
COL SQL_TEXT FOR A65

BREAK ON B1 NODUP ON C1 NODUP ON C2 NODUP ON B2 NODUP ON B3 NODUP  ON B4 NODUP ON B5 NODUP SKIP 5

SELECT C.SPID B1, 
	B.OSUSER C1, 
	B.USERNAME C2, 
	B.SID B2, 
	B.SERIAL# B3, 
	B.STATUS B4, 
	TO_CHAR(B.LOGON_TIME, 'DD/MM/YYYY HH24:MI:SS') B5, 
	A.SQL_TEXT
FROM V$SQLTEXT A, 
	V$SESSION B, 
	V$PROCESS C
WHERE A.ADDRESS    = B.SQL_ADDRESS
  AND B.STATUS     = 'ACTIVE'
  AND B.PADDR      = C.ADDR
  AND A.HASH_VALUE = B.SQL_HASH_VALUE
  AND B.USERNAME IS NOT NULL
ORDER BY C.SPID,A.HASH_VALUE,A.PIECE;
