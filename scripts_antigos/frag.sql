undef owner
set long 20000 
set longchunksize 20000 
set pagesize 10000
set linesize 2500
col owner for a35
col TABLE_NAME for a45 
set heading on
SELECT A.OWNER,
       A.SEGMENT_NAME AS TABLE_NAME,
       --A.TABLESPACE_NAME,
       ROUND(A.BYTES/1024/1024, 0) AS SEGMENT_SIZE_MB,
       ROUND((B.BLOCKS * 8)/1024, 0) AS TABLE_SIZE_MB,
       ROUND((B.NUM_ROWS * B.AVG_ROW_LEN /1024/1024), 0) AS REAL_SIZE_MB,
       CASE
          WHEN ROUND((B.NUM_ROWS * B.AVG_ROW_LEN /1024/1024), 0) > ROUND(A.BYTES/1024/1024, 0) THEN 0 -- Se REAL_SIZE > SEGMENT_SIZE = PCT 0%
          WHEN ROUND((B.NUM_ROWS * B.AVG_ROW_LEN /1024/1024), 0) = 0 AND
                  ROUND(A.BYTES/1024/1024, 0) < 20 THEN 0 -- Se REAL_SIZE = 0 e SEGMENT_SIZE < 20MB = PCT 0%
          WHEN ROUND(A.BYTES/1024/1024, 0) < 20 THEN 0 -- Se SEGMENT_SIZE < 20MB = PCT 0%
          WHEN ROUND((B.NUM_ROWS * B.AVG_ROW_LEN /1024/1024), 0) = 0 THEN 100 -- Se REAL_SIZE = 0, = PCT 100%
          ELSE ROUND(100-(ROUND(B.NUM_ROWS * B.AVG_ROW_LEN /1024/1024) / ROUND(A.BYTES/1024/1024, 0)) * 100, 0)
                                    -- Sen�o 100 - (REAL_SIZE / SEGMENT_SIZE) * 100 = C�lculo PCT xxx%
       END AS FRAGMENT_PCT, -- Se PCT > 20%, a fragmenta��o est� alta
       -- A.EXTENTS,
       B.NUM_ROWS,
       TO_CHAR(B.LAST_ANALYZED, 'DD/MM/YYYY HH:MI:SS AM') AS LAST_ANALYZED
  FROM DBA_SEGMENTS A,
       DBA_TABLES B
WHERE A.SEGMENT_NAME = B.TABLE_NAME
   AND A.OWNER = B.OWNER
ORDER BY FRAGMENT_PCT DESC, SEGMENT_SIZE_MB DESC, A.SEGMENT_NAME, A.TABLESPACE_NAME;
