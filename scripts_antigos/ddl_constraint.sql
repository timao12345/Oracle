-- Pegar o DDL da Constraint

UNDEF TABLE_NAME
UNDEF OWNER

COL DDL FOR A150
SELECT DBMS_METADATA.GET_DEPENDENT_DDL('REF_CONSTRAINT','&&TABLE_NAME','&&OWNER') DDL
FROM DBA_TABLES T
WHERE TABLE_NAME = 'FO_CUENTAS' AND OWNER = 'KIPREV'
AND EXISTS (SELECT 1
FROM DBA_CONSTRAINTS
WHERE TABLE_NAME = T.TABLE_NAME
AND CONSTRAINT_TYPE = 'R');





