-- SIZE ARCHIVES

SET PAGES 500 LINES 120

SELECT FIRST_TIME, 
		QTY, QTY * BYTES / 1048576 AS MB
FROM (SELECT TO_CHAR (FIRST_TIME, 'YYYY/MM/DD HH24') AS FIRST_TIME,
		COUNT (*) AS QTY
		FROM V$LOG_HISTORY
		GROUP BY TO_CHAR (FIRST_TIME, 'YYYY/MM/DD HH24')),
			(SELECT BYTES
            FROM V$LOG
			WHERE ROWNUM < 2)
			ORDER BY FIRST_TIME;


