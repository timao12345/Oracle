-- MOSTRA A QUERY QUE O USUÁRIO ESTÁ EXECUTANDO.

SET LINES 300 PAGES 5000
SET LONG 3000
COL USERNAME 	FOR A15
COL OSUSER 		FOR A15
COL SQL_ID		FOR A15 HEADING 'SQL|ID'
COL LOGON_TIME 	FOR A20 HEADING 'LOGON|TIME'

BREAK ON USERNAME NODUP ON SID NODUP ON SERIAL# NODUP ON STATUS NODUP ON OSUSER NODUP ON SQL_ID NODUP ON LOGON_TIME NODUP SKIP 5

UNDEF SQL_ID
SELECT A.USERNAME, 
	A.SID, 
	A.SERIAL#, 
	A.STATUS,
	A.OSUSER,
	B.SQL_ID, 
	A.LOGON_TIME,
	B.SQL_TEXT
FROM V$SESSION A, 
	V$SQLTEXT B
WHERE A.SQL_HASH_VALUE=B.HASH_VALUE
AND A.SQL_ID='&SQL_ID';
ORDER BY PIECE
