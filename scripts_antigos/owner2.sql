-- Informações do usuário.

UNDEF OWNER
ALTER SESSION SET NLS_DATE_FORMAT = 'DD/MM/YYYY HH24:MI:SS';
SET PAGES 1000
SET LINES 400
COL OSUSER FOR A15
SELECT 
	U.USERNAME,
	S.SID, 
	S.SERIAL#, 
	S.STATUS, 
	S.OSUSER, 
	U.PASSWORD, 
	U.ACCOUNT_STATUS, 
	U.DEFAULT_TABLESPACE,
	U.CREATED,U.PROFILE, 
	S.LOGON_TIME 
FROM 
	DBA_USERS U, 
	V$SESSION S 
WHERE 
	U.USERNAME=UPPER ('&&OWNER');