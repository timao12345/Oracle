SET LINESIZE 150
COL OWNER FOR A25
COL OBJECT FOR A40
COL USERNAME FOR A15
COL TYPE FOR A15
COL STATUS FOR A10

SELECT A.SID, 
	   A.USERNAME, 
	   B.OWNER, 
	   B.OBJECT, 
	   B.TYPE, 
	   A.STATUS
FROM   V$SESSION A, 
       V$ACCESS B
WHERE  A.SID = B.SID
AND    B.TYPE = 'PACKAGE'
AND    B.OWNER='OPSS'
--AND  A.USERNAME = 'WEB'
AND    B.OBJECT ='PG_DASHBOARD_GERENCIAL';
