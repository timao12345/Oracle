-- Formata o sql_text
SET LONG 20000 LONGCHUNKSIZE 20000 PAGESIZE 0 LINESIZE 1000 FEEDBACK OFF VERIFY OFF TRIMSPOOL ON

begin
DBMS_METADATA.set_transform_param (DBMS_METADATA.session_transform,'SQLTERMINATOR',true);
end;
/


begin
DBMS_METADATA.set_transform_param (DBMS_METADATA.session_transform,'PRETTY',true);
end;
/

-- Acha a Query desejada a partir do SID

SET LINES 300 PAGES 5000
SET LONG 3000
COL USERNAME 	FOR A15
COL OSUSER 		FOR A15
COL SQL_ID		FOR A15 HEADING 'SQL|ID'
COL LOGON_TIME 	FOR A20 HEADING 'LOGON|TIME'
COL SQL_TEXT	FOR A90

BREAK ON USERNAME NODUP ON SID NODUP ON SERIAL# NODUP ON STATUS NODUP ON OSUSER NODUP ON SQL_ID NODUP ON LOGON_TIME NODUP SKIP 5

UNDEF SID
ALTER SESSION SET NLS_DATE_FORMAT='dd/mm/yy:hh24:mi:ss';
SELECT A.USERNAME, 
	A.SID, 
	A.SERIAL#, 
	A.STATUS,
	A.OSUSER,
	B.SQL_ID, 
	A.LOGON_TIME,
	B.SQL_TEXT
FROM V$SESSION A, 
	V$SQLTEXT B
WHERE A.SQL_HASH_VALUE=B.HASH_VALUE
AND SID=&&SID
ORDER BY PIECE
/