-- SPID

UNDEF SPID

SET LINES 300
COL SPID FOR A5
COL PROGRAM FOR A20
COL MACHINE FOR A30
SELECT A.USERNAME,
	A.SID, 
	A.SERIAL#, 
	B.SPID, 
	A.STATUS, 
	A.OSUSER, 
	A.MACHINE, 
	A.PROGRAM, 
	TO_CHAR(A.LOGON_TIME,'DD-MM-RR HH24:MI:SS') LOGON_TIME, 
	A.LAST_CALL_ET AS L_C_I
FROM V$SESSION A,
	V$PROCESS B
WHERE B.SPID = &SPID
AND A.PADDR=B.ADDR;

