PROMPT 'CHECK THE STATUS OF DATABASE RMAN'

SET PAGES 400 LINES 200
COL START_TIME 		FOR A20 		HEADING 'START|TIME'
COL END_TIME  		FOR A20		    HEADING 'END|TIME'
COL OPERATION 		FOR A10 TRUNC
COL OBJECT_TYPE      				HEADING 'OBJECT|TYPE'
COL STATUS 			FOR A25
COL SESSION_STAMP   FOR 9999999999  HEADING 'SESSION|STAMP'
COL MBYTES_PROCESSED				HEADING 'MB|COPIED'
COL OUTPUT_DEVICE_TYPE				HEADING 'OUTPUT|DEVICE_TYPE'
COL GB_COPIADOS 	FOR 9,999,999.99

SELECT 
	TO_CHAR(START_TIME,'DD/MM HH24:MI:SS dy') START_TIME, 
	TO_CHAR(END_TIME,'DD/MM HH24:MI:SS dy') END_TIME, 
	OPERATION,
	OBJECT_TYPE, 
	STATUS,
	MBYTES_PROCESSED,
	OUTPUT_DEVICE_TYPE,
	SESSION_STAMP
FROM V$RMAN_STATUS 
WHERE START_TIME > SYSDATE -10 
AND OPERATION='BACKUP' 
ORDER  BY START_TIME DESC 
/

PROMPT 'CHECK THE LOG'

SELECT OUTPUT FROM V$RMAN_OUTPUT
WHERE SESSION_STAMP LIKE '&SESSION_STAMP%'
/
