-- Informações do usuário.

COL USERNAME FOR A20
COL ACCOUNT_STATUS FOR A10 				HEADING 'ACCOUNT|STATUS'
COL LOCK_DATE FOR a10 					HEADING 'LOCK|DATE'
COL DEFAULT_TABLESPACE FOR A20 			HEADING 'DEFAULT|TABLESPACE'
COL INITIAL_RSRC_CONSUMER_GROUP FOR A30 HEADING 'I_C_G'
COL CREATED FOR A10 					HEADING 'CREATED'

ALTER SESSION SET NLS_DATE_FORMAT='dd/mm/yyyy hh24:mi:ss';

UNDEF OWNER
SET LINES 400
SELECT 
	USERNAME, 
	PASSWORD, 
	ACCOUNT_STATUS,
	LOCK_DATE,
	DEFAULT_TABLESPACE,
	CREATED,
	PROFILE,
	INITIAL_RSRC_CONSUMER_GROUP 
FROM 
	DBA_USERS 
WHERE 
	USERNAME=UPPER ('&&OWNER');