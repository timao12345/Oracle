UNDEF SID

SET LINES 300
COL USERNAME FOR A10
COL SPID FOR A10
COL OSUSER FOR A10
COL PROGRAM FOR A30
COL MACHINE FOR A30
COL LOGON_TIME FOR A20 HEADING 'LOGON|TIME'

SELECT 
	A.USERNAME,
	A.SID, 
	A.SERIAL#, 
	B.SPID, 
	A.STATUS, 
	A.OSUSER, 
	A.MACHINE, 
	A.PROGRAM, 
	TO_CHAR(A.LOGON_TIME,'DD-MM-RR HH24:MI:SS') LOGON_TIME, 
	A.LAST_CALL_ET AS L_C_I,
	A.EVENT
FROM V$SESSION A,
	V$PROCESS B 
WHERE A.SID = '&SID' 
AND A.PADDR=B.ADDR;