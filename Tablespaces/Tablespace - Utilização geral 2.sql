ALTER SESSION SET NLS_NUMERIC_CHARACTERS=',.';
SET LINES 500 PAGES 500
COLUMN TABLESPACE   FORMAT A30
COLUMN BIG_FILE     FORMAT A8
COLUMN AUTO_EXT     FORMAT A8
COLUMN MAXSIZE_MB   FORMAT 999G999G990D99
COLUMN TOTAL_MB     FORMAT 999G999G990D99
COLUMN USED_MB      FORMAT 999G999G990D99
COLUMN FREE_MB      FORMAT 999G999G990D99
COLUMN PCT_OF_TOTAL FORMAT 900D99
COLUMN PCT_OF_MAX   FORMAT 900D99
COLUMN STATUS       FORMAT A10
SELECT
    TOTAL.TS TABLESPACE,
    VTAB.BIGFILE BIG_FILE,
    NVL2(MAXSIZE.MB,'YES','NO') AUTO_EXT,
    DECODE(TOTAL.MB,NULL,'OFFLINE',DECODE(DBAT.CONTENTS,'PERMANENT','ONLINE',DBAT.CONTENTS)) STATUS,
    NVL(TOTAL.MB+MAXSIZE.MB,TOTAL.MB) MAXSIZE_MB,
    TOTAL.MB TOTAL_MB,
    NVL(TOTAL.MB - FREE.MB,TOTAL.MB) USED_MB,
    NVL(FREE.MB,0) FREE_MB,
    DECODE(TOTAL.MB,NULL,0,NVL(ROUND((TOTAL.MB - FREE.MB)/(TOTAL.MB)*100,2),100)) PCT_OF_TOTAL,
    CASE NVL(MAXSIZE.MB,0)
        WHEN 0 THEN DECODE(TOTAL.MB,NULL,0,NVL(ROUND((TOTAL.MB - FREE.MB)/(TOTAL.MB)*100,2),100))
        ELSE DECODE(TOTAL.MB,NULL,0,NVL(ROUND((TOTAL.MB - FREE.MB)/(TOTAL.MB+MAXSIZE.MB)*100,2),100))
    END PCT_OF_MAX
FROM
    (SELECT TABLESPACE_NAME TS, SUM(BYTES)/1024/1024 MB FROM DBA_DATA_FILES GROUP BY TABLESPACE_NAME) TOTAL,
    (SELECT TABLESPACE_NAME TS, SUM(BYTES)/1024/1024 MB FROM DBA_FREE_SPACE GROUP BY TABLESPACE_NAME) FREE,
    (SELECT TABLESPACE_NAME TS, NVL((SUM(MAXBYTES)-SUM(BYTES))/1024/1024,0) MB
        FROM DBA_DATA_FILES WHERE MAXBYTES>BYTES GROUP BY TABLESPACE_NAME) MAXSIZE,
    DBA_TABLESPACES DBAT,
    V$TABLESPACE VTAB
WHERE
    TOTAL.TS=FREE.TS(+) AND
    TOTAL.TS=DBAT.TABLESPACE_NAME AND
    TOTAL.TS=MAXSIZE.TS(+) AND
    DBAT.TABLESPACE_NAME=VTAB.NAME
UNION ALL
SELECT
    SH.TABLESPACE_NAME,
    NULL,
    NULL,
    'TEMP',
    NULL,
    SUM(SH.BYTES_USED+SH.BYTES_FREE)/1024/1024 TOTAL_MB,
    SUM(SH.BYTES_USED)/1024/1024 USED_MB,
    SUM(SH.BYTES_FREE)/1024/1024 FREE_MB,
    ROUND(SUM(SH.BYTES_USED)/SUM(SH.BYTES_USED+SH.BYTES_FREE)*100,2),
    NULL
FROM V$TEMP_SPACE_HEADER SH
GROUP BY TABLESPACE_NAME
ORDER BY 9
