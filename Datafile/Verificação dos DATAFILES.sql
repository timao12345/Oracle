COLUMN FILE_ID      FORMAT 9999999
COLUMN FILE_NAME    FORMAT A80
COLUMN STATUS       FORMAT A10
COLUMN SIZE_MB      FORMAT 999,999,999.99
COLUMN MAXSIZE_MB   FORMAT 999,999,999.99
COLUMN AUTO_EXT     FORMAT A8
COLUMN INCR_MB      FORMAT 999,999.99
SELECT
    FILE_ID, FILE_NAME,STATUS, 
    TRUNC(DF.BYTES/1024/1024) "SIZE_MB",
    TRUNC(DF.MAXBYTES/1024/1024) "MAXSIZE_MB",
    DF.AUTOEXTENSIBLE "AUTO_EXT",
    CEIL(DF.INCREMENT_BY*BLOCK.VALUE/1024/1024) "INCR_MB"
FROM
    DBA_DATA_FILES DF,
    (SELECT VALUE FROM V$PARAMETER WHERE NAME='db_block_size') BLOCK
WHERE TABLESPACE_NAME = '&TABLESPACE_NAME'
ORDER BY 1
