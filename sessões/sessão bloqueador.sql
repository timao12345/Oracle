SET LINES 300 PAGES 300
COL INST_ID FOR 99999 			HEADING 'INST|BLOQUEADOR'
COL SPID FOR 999999 
COL BLOQUEADO FOR A30
COL USER_BLOQUEADOR  FOR A12 	HEADING 'USER|BLOQUEADOR'
COL SESSAO_BLOQUEADORA FOR A49 	HEADING 'SESSAO|BLOQUEADORA'
COL USER_BLOQUEADOR FOR A15		HEADING 'USER|BLOQUEADOR'
COL OSUSER_BLOQUEADO FOR A20	HEADING 'OSUSER|BLOQUEADO'
COL PROGRAM FOR A30
COL OSUSER FOR A15
COL EVENT FOR A40
 
SELECT  DISTINCT
    S.INST_ID,
    S.USERNAME ||   ' ''' || S.SID || ',' || S.SERIAL# || ''''  BLOQUEADO,
    S.OSUSER AS OSUSER_BLOQUEADO,
	S.EVENT,
	N.USERNAME USER_BLOQUEADOR,
	N.INST_ID,
	'ALTER SYSTEM KILL SESSION ''' || N.SID || ',' || N.SERIAL# || ''' IMMEDIATE;' SESSAO_BLOQUEADORA,
	N.OSUSER,
	N.SQL_HASH_VALUE SQL_BLOQUEADOR,
	N.PROGRAM
FROM
   GV$SESSION S,  -- DADOS DO BLOQUEADO
   GV$SESSION N, -- DADOS DO BLOQUEADOR.
   GV$PROCESS P
WHERE
     S.PADDR = P.ADDR
AND S.BLOCKING_SESSION IS NOT NULL
AND N.SID=S.BLOCKING_SESSION;
