-- Verificar os archives aplicados per date.
SET LINES 900 PAGES 900
COL COMPLETION_TIME FOR A25

UNDEF DATE THREAD
SELECT TO_CHAR(COMPLETION_TIME, 'DD/MM/YYYY HH24:MI:SS') COMPLETION_TIME, 
	THREAD#,
	DEST_ID, 
	SEQUENCE#, 
	ARCHIVED, 
	APPLIED, 
	DELETED
FROM V$ARCHIVED_LOG 
WHERE COMPLETION_TIME > SYSDATE-&&DATE
AND THREAD#=&&THREAD
ORDER BY SEQUENCE#;