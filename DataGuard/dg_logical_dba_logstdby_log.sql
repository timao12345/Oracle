-- VERIFICAR ULTIMA SEQUENCE APLICADA NA COLUNA APPLIED 
ALTER SESSION SET NLS_DATE_FORMAT='DD/MM/YYYY HH24:MI:SS';

SET LINES 255 PAGES 200
COL FCHANGE# FOR 9999999999999999
COL NCHANGE# FOR 99999999999999999
COL FILE_NAME FOR A80

SELECT FILE_NAME, 
	SEQUENCE# AS SEQ#, 
	FIRST_CHANGE# AS FCHANGE#, -- 	System change number (SCN) of the current archive log
	NEXT_CHANGE# AS NCHANGE#,  -- SCN of the next archive log
	TIMESTAMP,
	THREAD# AS THR#,
	APPLIED
FROM DBA_LOGSTDBY_LOG
ORDER BY SEQUENCE#;