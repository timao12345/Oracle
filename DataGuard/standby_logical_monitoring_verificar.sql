The SESSION_ID column identifies the persistent LogMiner session created by SQL Apply to mine the archived redo log files generated by 
the primary database.

Waiting for Dictionary Logs

The first time the SQL Apply is started, it needs to load the LogMiner MultiVersioned Data Dictionary captured in the redo log files. 
SQL Apply will stay in the WAITING FOR DICTIONARY LOGS state until it has received all redo data required to load the 
LogMiner MultiVersioned Data Dictionary.

Loading Dictionary State

This loading dictionary state can persist for a while. Loading the LogMiner multiversioned data dictionary on a large database can take a long time. 
Querying the V$LOGSTDBY_STATE view returns the following output when loading the dictionary:

SQL> SELECT SESSION_ID, STATE FROM V$LOGSTDBY_STATE;

SESSION_ID    STATE
----------    ------------------
1             LOADING DICTIONARY
Only the COORDINATOR process and the mining processes are spawned until the LogMiner dictionary is fully loaded. 
Therefore, if you query the V$LOGSTDBY_PROCESS at this point, you will not see any of the APPLIER processes. For example:

SQL> SELECT SID, SERIAL#, SPID, TYPE FROM V$LOGSTDBY_PROCESS;

