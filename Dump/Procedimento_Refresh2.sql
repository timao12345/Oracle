--VER ANDAMENTO DO REFRESH
set lines 1000
col INICIO for a17
col FIM for a17
col PROGRAM_EM_EXEC for a32
col SCHEMA for a15
col TABELA for a30
col DB_LINK for a15
col CLAUSULA_WHERE for a30
col ACAO_PROGRAMA for a30
select * from(
SELECT TO_CHAR(DAT_EXEC_INI,'DD/MM/YY HH24:MI:SS') AS INICIO,
TO_CHAR(DAT_EXEC_FIM,'DD/MM/YY HH24:MI:SS') AS FIM,
round((DAT_EXEC_FIM-DAT_EXEC_INI)*24*60) AS TEMPO_TOTAL,
TXT_PAR02 AS SCHEMA,
TXT_PAR01 AS PROGRAM_EM_EXEC,
TXT_PAR03 AS TABELA,
TXT_PAR04 AS DB_LINK,
TXT_PAR05 AS CLAUSULA_WHERE,
TXT_PAR06 AS ACAO_PROGRAMA
from ORASTATUS.TBL_LOG where cod_resu not in(-942,-30657,-2298,-2293)
and dat_exec_ini >= to_date('12122014:2000','ddmmyyyy:hh24mi')
ORDER BY DAT_EXEC_fim desc) where  rownum < 30;


