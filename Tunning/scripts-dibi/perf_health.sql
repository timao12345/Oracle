SELECT
    SUBSTR(DECODE(REQUEST,0,'HOLDER','WAITER'),1,12) TYPE,
    S.SID SID,
    S.SERIAL#,
    L.INST_ID,
    S.USERNAME,
    S.OSUSER,
    S.STATUS,
    S.PROGRAM,
    S.EVENT,
    S.MACHINE,
    L.CTIME/60 TIME
