SET LINES 900
COL USERNAME FOR A10
COL MACHINE FOR A30
COL OPNAME FOR A30
COL MODULE FOR A20
COL TARGET FOR A20
SELECT A.SID, 
	A.SERIAL#,
	B.USERNAME,
	B.MODULE,
	B.MACHINE,
	A.OPNAME, 
	A.TARGET, 
	A.START_TIME, 
	A.TIME_REMAINING, ROUND(SOFAR/TOTALWORK*100,2) PERC
FROM V$SESSION_LONGOPS A, 
	V$SESSION B
WHERE TOTALWORK <> SOFAR
AND A.SID=B.SID
ORDER BY START_TIME DESC;
