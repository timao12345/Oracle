col WAIT_EVENT for a35
col USUARIO for a20
col CONSULTA for a45
col OSUSER for a20

SELECT s.INST_ID, W.SID SID, S.SERIAL# SERIAL, S.USERNAME USUARIO, S.OSUSER, W.EVENT WAIT_EVENT, W.SECONDS_IN_WAIT TEMPO_WAIT, SQL.SQL_TEXT CONSULTA, S.SQL_ID
FROM   GV$SESSION_WAIT W, GV$SESSION S, GV$PROCESS P, GV$SQLTEXT SQL
WHERE W.SID =  S.SID AND S.PADDR = P.ADDR
AND SQL.ADDRESS =S.SQL_ADDRESS
AND  SQL.HASH_VALUE = S.SQL_HASH_VALUE
AND W.WAIT_CLASS != 'Idle'
ORDER BY  W.SECONDS_IN_WAIT, W.SID, SQL.PIECE;
